def check(name, lines, expect):
    got = M._table_courses(lines)
    assert len(got) == len(expect), f"{name}: 得到 {len(got)} 门，期望 {len(expect)} 门\n{got}"
    for g, e in zip(got, expect):
        for k, v in e.items():
            assert g[k] == v, f"{name}.{k}: {g[k]!r} != {v!r}"
    print("PASS", name, len(got), "门")


